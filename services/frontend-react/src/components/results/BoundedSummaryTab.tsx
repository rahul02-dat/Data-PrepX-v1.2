import React, { useState } from "react";
import { BoundedSummaryReport } from "../../api/types";
import { Card } from "../common/Card";
import { Badge } from "../common/Badge";
import { Button } from "../common/Button";

interface BoundedSummaryTabProps {
  summary: BoundedSummaryReport;
}

export const BoundedSummaryTab: React.FC<BoundedSummaryTabProps> = ({ summary }) => {
  const [showGrounding, setShowGrounding] = useState(false);

  return (
    <div style={{ display: "flex", flexDirection: "column", gap: "20px" }}>
      {/* Executive Report Card */}
      <Card
        title="Bounded Reasoning Natural-Language Report"
        subtitle={`Generated by ${summary.model_name} with strict deterministic claim verification`}
        action={
          <Button variant="secondary" onClick={() => setShowGrounding(!showGrounding)}>
            {showGrounding ? "Hide Grounding Stats" : "Inspect Grounding Stats"}
          </Button>
        }
      >
        <div
          style={{
            padding: "16px",
            background: "rgba(15, 23, 42, 0.6)",
            borderRadius: "var(--radius-md)",
            border: "1px solid var(--border-subtle)",
            lineHeight: "1.7",
            fontSize: "14px",
            color: "var(--text-primary)",
          }}
        >
          {summary.summary_text}
        </div>

        {showGrounding && (
          <div style={{ marginTop: "16px" }}>
            <h4 style={{ fontSize: "12px", fontWeight: 700, textTransform: "uppercase", color: "var(--text-muted)", marginBottom: "8px" }}>
              Grounding Deterministic Statistics
            </h4>
            <pre
              style={{
                fontFamily: "var(--font-mono)",
                fontSize: "11px",
                background: "#080c14",
                padding: "12px",
                borderRadius: "6px",
                color: "var(--accent-cyan)",
                border: "1px solid var(--border-subtle)",
                overflowX: "auto",
              }}
            >
              {JSON.stringify(summary.grounding_stats, null, 2)}
            </pre>
          </div>
        )}
      </Card>

      {/* Verified Claims Breakdown */}
      <Card
        title="Verifiable Assertions & Confidence Badges"
        subtitle="Every drafted numeric claim is deterministically verified against computed pipeline statistics"
      >
        <div style={{ display: "flex", flexDirection: "column", gap: "12px" }}>
          {summary.claims.map((claim) => {
            const badgeVariant =
              claim.confidence_level === "HIGH"
                ? "green"
                : claim.confidence_level === "MODERATE"
                ? "yellow"
                : "red";

            return (
              <div
                key={claim.id}
                style={{
                  background: "rgba(15, 23, 42, 0.7)",
                  border: "1px solid var(--border-subtle)",
                  borderRadius: "var(--radius-md)",
                  padding: "14px",
                  display: "flex",
                  flexDirection: "column",
                  gap: "8px",
                }}
              >
                <div style={{ display: "flex", justifyContent: "space-between", alignItems: "flex-start", gap: "12px" }}>
                  <span style={{ fontSize: "13px", fontWeight: 600, color: "var(--text-primary)" }}>
                    "{claim.text}"
                  </span>
                  <Badge variant={badgeVariant}>
                    {claim.confidence_level} ({Math.round(claim.confidence_score * 100)}%)
                  </Badge>
                </div>

                <div
                  style={{
                    display: "flex",
                    flexWrap: "wrap",
                    gap: "12px",
                    fontSize: "11px",
                    fontFamily: "var(--font-mono)",
                    background: "#080c14",
                    padding: "8px 12px",
                    borderRadius: "6px",
                    border: "1px solid var(--border-subtle)",
                  }}
                >
                  <span style={{ color: "var(--text-muted)" }}>
                    Metric: <strong style={{ color: "var(--text-primary)" }}>{claim.verifiable_metric}</strong>
                  </span>
                  <span style={{ color: "var(--text-muted)" }}>
                    Value: <strong style={{ color: "var(--accent-emerald)" }}>{String(claim.computed_value)}</strong>
                  </span>
                  {claim.p_value_or_ci && (
                    <span style={{ color: "var(--text-muted)" }}>
                      Stats: <strong style={{ color: "var(--accent-cyan)" }}>{claim.p_value_or_ci}</strong>
                    </span>
                  )}
                  <span style={{ color: claim.verification_passed ? "var(--accent-emerald)" : "var(--accent-rose)", fontWeight: 700 }}>
                    {claim.verification_passed ? "✓ Deterministically Verified" : "✗ Verification Failed"}
                  </span>
                </div>
              </div>
            );
          })}
        </div>
      </Card>
    </div>
  );
};
